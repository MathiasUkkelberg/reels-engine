/**
 * npm run demo:learn: run the learning loop on SYNTHETIC data (in-memory DB) to show what the
 * reports, dashboard and playbook look like after ~2 months of posting. Writes to examples/demo-learning/.
 * Nothing here touches data/reels.db.
 */
import fs from 'node:fs';
import path from 'node:path';
import { paths } from '../paths.ts';
import { openDb, upsertReel, markPosted, insertSnapshot, upsertHypothesis } from '../db/index.ts';
import { loadSpecFile } from '../spec/validate.ts';
import type { Spec } from '../spec/schema.ts';
import { runLearn } from '../learn/pipeline.ts';
import { rng, randn } from '../learn/stats.ts';

/** Hidden "truth" used to generate the synthetic metrics (log2 effects on shares/saves/watch-through). */
const TRUTH: Record<string, number> = {
  'template=terminal': 0.7,
  'template=chat': 0.45,
  'template=progress': 0.3,
  'template=keynote': -0.45,
  'template=expectation_reality': -0.25,
  'hook_type=relatable_pain': 0.3,
  'loop=true': 0.35,
  'long=true': -0.5,
};

export async function demoLearnCmd(args: string[]) {
  const n = Number(args[0] ?? 64);
  const r = rng(2026);
  const db = openDb(':memory:');
  const dir = path.join(paths.examples, 'specs');
  const bases = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => loadSpecFile(path.join(dir, f)));
  const start = Date.UTC(2026, 8, 1, 10, 5);
  let followers = 1200;
  for (let i = 0; i < n; i++) {
    const base = bases[Math.floor(r() * bases.length)];
    const loop = r() < 0.35;
    const duration = [8, 10, 12, 14, 17, 19][Math.floor(r() * 6)];
    const spec = structuredClone(base) as Spec;
    spec.id = `demo-${String(i + 1).padStart(3, '0')}-${base.template}`;
    spec.loop = loop;
    spec.duration_s = duration;
    spec.features = { ...spec.features, loop, length_s: duration, hook_type: r() < 0.45 ? 'relatable_pain' : spec.features.hook_type };
    spec.experiment = r() < 0.3 ? { arm: 'explore', hypothesis_id: `template-${base.template}`, hypothesis: `Reels with template "${base.template}" score above the account median` } : { arm: 'exploit' };
    spec.source = 'example';
    upsertReel(db, spec, 'rendered');
    if (spec.experiment.hypothesis_id) upsertHypothesis(db, { id: spec.experiment.hypothesis_id, statement: spec.experiment.hypothesis!, feature: 'template', value: base.template });
    const postedAt = new Date(start + Math.floor(i / 2) * 86400e3 + (i % 2) * 9.5 * 3600e3);
    markPosted(db, spec.id, `demo${i}`, postedAt.toISOString());
    let eff = randn(r) * 0.45;
    const on = (k: string) => (TRUTH[k] ?? 0);
    eff += on(`template=${spec.template}`) + (spec.features.hook_type === 'relatable_pain' ? on('hook_type=relatable_pain') : 0) + (loop ? on('loop=true') : 0) + (duration >= 15 ? on('long=true') : 0);
    const mult = 2 ** eff;
    const reach = Math.round(followers * (2.5 + r() * 3) * Math.sqrt(mult));
    followers += Math.round(reach * 0.004 * mult);
    insertSnapshot(db, {
      reel_id: spec.id,
      captured_at: new Date(postedAt.getTime() + 72 * 3600e3).toISOString(),
      age_hours: 72,
      bucket: '72h',
      reach,
      views: Math.round(reach * 1.5),
      likes: Math.round(reach * 0.055 * mult ** 0.5),
      comments: Math.round(reach * 0.004 * mult ** 0.6),
      shares: Math.round(reach * 0.009 * mult),
      saves: Math.round(reach * 0.004 * mult),
      avg_watch_time_s: Math.min(duration * 2.2, duration * 0.62 * mult ** 0.4),
      source: 'csv',
    });
  }
  db.prepare('INSERT INTO account_snapshots (captured_at, followers) VALUES (?, ?)').run(new Date(start + (n / 2) * 86400e3).toISOString(), followers);

  const out = path.join(paths.examples, 'demo-learning');
  fs.mkdirSync(out, { recursive: true });
  const res = runLearn({ db, date: 'demo', outDirs: { reports: out, playbook: path.join(out, 'PLAYBOOK.md'), insights: path.join(out, 'insights.json') } });
  const banner = `> **SYNTHETIC DEMO DATA.** Generated by \`npm run demo:learn\` from ${n} fake reels with known effects (${Object.entries(TRUTH)
    .map(([k, v]) => `${k} ${v > 0 ? '+' : ''}${Math.round((2 ** v - 1) * 100)}%`)
    .join(', ')}). It shows what the learning loop outputs look like; it says nothing about the real account.\n\n`;
  for (const f of ['PLAYBOOK.md', 'demo.md']) {
    const p = path.join(out, f);
    fs.writeFileSync(p, banner + fs.readFileSync(p, 'utf8'));
  }
  fs.renameSync(path.join(out, 'demo.md'), path.join(out, 'report.md'));
  const dash = path.join(out, 'dashboard.html');
  fs.writeFileSync(dash, fs.readFileSync(dash, 'utf8').replace('<main>', '<main><p style="background:#ffb547;color:#000;padding:8px 12px;border-radius:8px"><b>Synthetic demo data</b> (npm run demo:learn): not real account metrics.</p>'));
  fs.rmSync(path.join(out, 'insights.json'), { force: true });
  console.log(`Demo: ${res.insights.n_scored} synthetic reels scored (mode=${res.insights.analysis.mode}). Wrote ${path.relative(process.cwd(), out)}/{PLAYBOOK.md,report.md,dashboard.html}`);
}
